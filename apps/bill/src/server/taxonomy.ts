/** 账户名归一化时先剥掉的渠道前缀（微信账单的支付方式常带「微信-」） */
const ACCOUNT_PREFIX_RULES: Array<[RegExp, string]> = [[/^微信-/, ""]];

/**
 * 按账户名猜账户类型。
 *
 * 注意：这里对「信用卡」返回的是 BANK —— 与原实现一致（源库里唯一那条
 * CREDIT 账户是历史数据，不是这个函数产生的）。改动前先确认会不会影响新建账户。
 */
export function accountKindOf(name: string | null | undefined): BillAccountKind {
  const s = name || "";
  if (s.includes("微信") || s.includes("零钱")) return "WECHAT";
  if (s.includes("支付宝") || s.includes("余额宝") || s.includes("花呗")) return "ALIPAY";
  if (s.includes("京东") || s.includes("白条") || s.includes("小金库")) return "JD";
  if (s.includes("银行") || s.includes("信用卡") || s.includes("银联") || s.includes("云闪付")) {
    return "BANK";
  }
  if (s.includes("现金")) return "CASH";
  return "OTHER";
}

/**
 * 把账单里的账户名收敛成统一账户名：
 * 1) 去掉「&红包」「&奖励金抵扣」这类优惠组合后缀
 * 2) 去掉「微信-」这类渠道前缀
 * 3) 银行全称统一（中国工商银行 → 工商银行）
 */
export function normalizeAccountName(name: string | null | undefined): string {
  let s = String(name || "").trim();
  if (!s || s === "/") return "";
  s = s.split("&")[0].trim();
  s = s.replace(/\s+/g, " ");
  for (const [pattern, replacement] of ACCOUNT_PREFIX_RULES) {
    if (pattern.test(s)) {
      s = replacement ? replacement + s.replace(pattern, "") : s.replace(pattern, "");
      break;
    }
  }
  if (/^账户余额/.test(s) || /^余额(?!宝)/.test(s)) s = "支付宝余额";
  s = s.replace(/^中国(?!人民)/, "");
  return s;
}

/** 外部分类名 → [一级, 二级]。带空格的复合分类取第一段。 */
export function resolveCategoryPath(
  name: string | null | undefined,
  kind: BillCategoryKind,
): [string, string?] | null {
  const raw = String(name || "").trim();
  if (!raw) return null;
  const table = EXTERNAL_CATEGORY[kind];
  if (!table) return null;
  if (table[raw]) return table[raw];
  const first = raw.split(/[\s/、,]+/)[0];
  if (table[first]) return table[first];
  return null;
}

export function categoryTreeEntries(kind: BillCategoryKind): Array<[string, string[]]> {
  return CATEGORY_TREE[kind] || [];
}

